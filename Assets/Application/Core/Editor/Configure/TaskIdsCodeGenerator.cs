#if UNITY_EDITOR
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

// Regenerates TaskProgressKeys / TaskRewardIds from whatever ProgressKey / RewardId
// strings exist across a TaskCatalog's TaskDefinitions, so gameplay code can write
// TaskProgressKeys.EnemiesKilled instead of a raw "enemies_killed" string. Called
// automatically by TaskEditorWindow (see its Add/Duplicate/Remove handlers and
// OnLostFocus/OnDisable) — the menu item below is a manual fallback, e.g. after
// editing a TaskCatalog directly in the Inspector instead of through that window.
public static class TaskIdsCodeGenerator
{
    private const string OutputPath = "Assets/Application/Core/Tasks/Generated/TaskIds.cs";

    [MenuItem("Tools/Regenerate/Task Ids")]
    public static void GenerateFromFirstCatalogInProject()
    {
        var guid = AssetDatabase.FindAssets("t:TaskCatalog").FirstOrDefault();
        if (guid == null)
        {
            Debug.LogWarning("[TaskIdsCodeGenerator] No TaskCatalog asset found in the project.");
            return;
        }

        Generate(AssetDatabase.LoadAssetAtPath<TaskCatalog>(AssetDatabase.GUIDToAssetPath(guid)));
    }

    public static void Generate(TaskCatalog catalog)
    {
        if (catalog == null) return;

        var progressKeys = catalog.Definitions.Select(d => d.ProgressKey);
        var rewardIds = catalog.Definitions.Select(d => d.RewardId);
        var paramKeys = catalog.Definitions.SelectMany(d => d.Conditions).Select(c => c.ParamKey);

        var code =
$@"// <auto-generated/>
// Regenerated from the TaskCatalog by the Task Editor window (Tools > Task Editor)
// whenever a task is added, duplicated, removed, or edited. Don't edit by hand — run
// Tools > Regenerate > Task Ids after changing a TaskCatalog outside that window.
public static class TaskProgressKeys
{{
{ToConstants(progressKeys)}
}}

public static class TaskRewardIds
{{
{ToConstants(rewardIds)}
}}

public static class TaskParamKeys
{{
{ToConstants(paramKeys)}
}}
";

        // Skip the write (and the recompile it triggers) when nothing actually changed.
        if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == code) return;

        Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));
        File.WriteAllText(OutputPath, code);
        AssetDatabase.Refresh();
    }

    private static string ToConstants(IEnumerable<string> rawKeys)
    {
        var used = new HashSet<string>();
        var lines = new List<string>();

        foreach (var raw in rawKeys.Where(k => !string.IsNullOrEmpty(k)).Distinct().OrderBy(k => k))
        {
            lines.Add($"    public const string {ToUniqueIdentifier(raw, used)} = \"{raw}\";");
        }

        return string.Join("\n", lines);
    }

    // Keys are free-typed by whoever authors tasks, so this both sanitizes them into
    // a valid identifier and de-duplicates identifiers that collide after sanitizing
    // (e.g. "coins" and "coins!" would otherwise both become "coins").
    private static string ToUniqueIdentifier(string raw, HashSet<string> used)
    {
        var cleaned = new string(raw.Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());
        if (cleaned.Length == 0 || char.IsDigit(cleaned[0])) cleaned = "_" + cleaned;

        var identifier = cleaned;
        var suffix = 2;
        while (!used.Add(identifier))
        {
            identifier = $"{cleaned}_{suffix++}";
        }

        return identifier;
    }
}
#endif
