#if UNITY_EDITOR
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

// Regenerates SoundIds from the ids in a SoundCatalog, so gameplay code can write
// SoundIds.Ui_Click instead of a raw "ui_click" string. Called automatically by
// SoundCatalogEditor - the menu item is a manual fallback, e.g. after editing the
// catalog outside the Inspector.
public static class SoundIdsCodeGenerator
{
    private const string DefaultOutputPath = "Assets/Application/Core/AudioNew/Generated/SoundIds.cs";

    [MenuItem("Tools/Regenerate/Sound Ids")]
    public static void GenerateFromFirstCatalogInProject()
    {
        var catalog = FindCatalog();
        if (catalog == null)
        {
            Debug.LogWarning("[SoundIdsCodeGenerator] No SoundCatalog asset found in the project.");
            return;
        }

        Generate(catalog);
    }

    public static SoundCatalog FindCatalog()
    {
        var guid = AssetDatabase.FindAssets("t:SoundCatalog").FirstOrDefault();
        return guid == null ? null : AssetDatabase.LoadAssetAtPath<SoundCatalog>(AssetDatabase.GUIDToAssetPath(guid));
    }

    public static void Generate(SoundCatalog catalog)
    {
        if (catalog == null) return;

        var used = new HashSet<string>();
        var lines = catalog.sounds
            .Where(s => s != null)
            .Select(s => s.Id)
            .Distinct(System.StringComparer.OrdinalIgnoreCase)
            .OrderBy(id => id)
            .Select(id => $"    public const string {ToUniqueIdentifier(id, used)} = \"{id.Replace("\"", "\\\"")}\";");

        var code =
$@"// <auto-generated/>
// Regenerated from the SoundCatalog by SoundCatalogEditor whenever the catalog is
// edited. Don't edit by hand - run Tools > Regenerate > Sound Ids after
// changing a SoundCatalog outside the Inspector.
public static class SoundIds
{{
{string.Join("\n", lines)}
}}
";

        var outputPath = FindOutputPath();

        // Skip the write (and the recompile it triggers) when nothing actually changed.
        if (File.Exists(outputPath) && File.ReadAllText(outputPath) == code) return;

        Directory.CreateDirectory(Path.GetDirectoryName(outputPath));
        File.WriteAllText(outputPath, code);
        AssetDatabase.ImportAsset(outputPath);
    }

    // Follows the existing SoundIds.cs if the audio folder was moved or renamed.
    private static string FindOutputPath()
    {
        var existing = AssetDatabase.FindAssets("SoundIds t:MonoScript")
            .Select(guid => AssetDatabase.GUIDToAssetPath(guid))
            .FirstOrDefault(p => Path.GetFileName(p) == "SoundIds.cs");
        return existing ?? DefaultOutputPath;
    }

    // Ids are free-typed, so this sanitizes them into valid identifiers and de-duplicates
    // ones that collide after sanitizing (e.g. "sfx-click" and "sfx click").
    private static string ToUniqueIdentifier(string raw, HashSet<string> used)
    {
        var cleaned = new string(raw.Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());
        if (cleaned.Length == 0 || char.IsDigit(cleaned[0])) cleaned = "_" + cleaned;

        var identifier = cleaned;
        var suffix = 2;
        while (!used.Add(identifier)) identifier = $"{cleaned}_{suffix++}";

        return identifier;
    }
}
#endif
