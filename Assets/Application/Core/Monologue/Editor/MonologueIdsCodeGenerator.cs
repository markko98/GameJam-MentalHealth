#if UNITY_EDITOR
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEngine;

// Writes MonologueIds from the catalogue's ids.
public static class MonologueIdsCodeGenerator
{
    private const string DefaultOutputPath = "Assets/Application/Core/Monologue/Generated/MonologueIds.cs";

    [MenuItem("Tools/Regenerate/Monologue Ids")]
    public static void GenerateFromFirstCatalogueInProject()
    {
        var catalogue = FindCatalogue();
        if (catalogue == null)
        {
            Debug.LogWarning("[MonologueIdsCodeGenerator] No MonologueCatalogue asset found in the project.");
            return;
        }

        Generate(catalogue);
    }

    public static MonologueCatalogue FindCatalogue()
    {
        var guid = AssetDatabase.FindAssets("t:MonologueCatalogue").FirstOrDefault();
        return guid == null ? null : AssetDatabase.LoadAssetAtPath<MonologueCatalogue>(AssetDatabase.GUIDToAssetPath(guid));
    }

    public static void Generate(MonologueCatalogue catalogue)
    {
        if (catalogue == null) return;

        var used = new HashSet<string>();
        var lines = catalogue.monologues
            .Where(monologue => monologue != null)
            .Select(monologue => monologue.Id)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(id => id)
            .Select(id => $"    public const string {ToUniqueIdentifier(id, used)} = \"{id.Replace("\"", "\\\"")}\";");

        var code =
$@"// <auto-generated/>
public static class MonologueIds
{{
{string.Join("\n", lines)}
}}
";

        var outputPath = FindOutputPath();

        if (File.Exists(outputPath) && File.ReadAllText(outputPath) == code) return;

        Directory.CreateDirectory(Path.GetDirectoryName(outputPath));
        File.WriteAllText(outputPath, code);
        AssetDatabase.ImportAsset(outputPath);
    }

    private static string FindOutputPath()
    {
        var existing = AssetDatabase.FindAssets("MonologueIds t:MonoScript")
            .Select(AssetDatabase.GUIDToAssetPath)
            .FirstOrDefault(path => Path.GetFileName(path) == "MonologueIds.cs");
        return existing ?? DefaultOutputPath;
    }

    private static string ToUniqueIdentifier(string raw, HashSet<string> used)
    {
        var cleaned = new string(raw.Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());
        if (cleaned.Length == 0 || char.IsDigit(cleaned[0])) cleaned = "_" + cleaned;

        var identifier = cleaned;
        var suffix = 2;
        while (!used.Add(identifier)) identifier = $"{cleaned}_{suffix++}";

        return identifier;
    }
}
#endif
